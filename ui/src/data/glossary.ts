export type GlossaryKey = keyof typeof glossaryCategories;

export interface GlossaryEntry {
  term: string;
  definition: string;
  category: (typeof glossaryCategories)[GlossaryKey];
}

export function getGlossary(t: TFunction<'help'>): GlossaryEntry[] {
  return (Object.keys(glossaryCategories) as GlossaryKey[]).map((key) => ({
    term: t(`glossary.${key}.term`),
    definition: t(`glossary.${key}.definition`),
    category: glossaryCategories[key],
  }));
}
